#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import readline from 'readline';
import { execSync } from 'child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const TEMPLATES = path.join(ROOT, 'templates');

const args = process.argv.slice(2);
function flag(name, fallback) {
  const i = args.indexOf(`--${name}`);
  if (i >= 0) return args[i + 1] || true;
  return fallback;
}

const yes = args.includes('--yes') || args.includes('-y');
const nameArg = args.find((a) => !a.startsWith('-'));

async function ask(q, def) {
  if (yes && def !== undefined) return def;
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const ans = await new Promise((res) => rl.question(`${q}${def ? ` (${def})` : ''}: `, res));
  rl.close();
  return (ans || def || '').trim();
}

function copyDir(src, dest, vars) {
  fs.mkdirSync(dest, { recursive: true });
  for (const ent of fs.readdirSync(src, { withFileTypes: true })) {
    if (ent.name === 'node_modules') continue;
    const s = path.join(src, ent.name);
    const d = path.join(dest, ent.name);
    if (ent.isDirectory()) copyDir(s, d, vars);
    else {
      let text = fs.readFileSync(s, 'utf8');
      for (const [k, v] of Object.entries(vars)) {
        text = text.split(`{{${k}}}`).join(v);
      }
      fs.writeFileSync(d, text);
    }
  }
}

function writeMergedRoot(target, cfg) {
  const pkg = {
    name: cfg.name,
    version: '1.0.0',
    private: true,
    workspaces: ['apps/*'],
    scripts: {
      dev: 'npm run dev -w apps/api & npm run dev -w apps/web',
      'dev:api': 'npm run dev -w apps/api',
      'dev:web': 'npm run dev -w apps/web',
      build: 'npm run build -w apps/web',
      test: 'npm run test -w apps/api',
      'db:push': 'npm run db:push -w apps/api',
    },
  };
  fs.writeFileSync(path.join(target, 'package.json'), JSON.stringify(pkg, null, 2));
  fs.writeFileSync(
    path.join(target, '.env.example'),
    `PORT=4000\nJWT_SECRET=change-me\nDATABASE_URL=file:./dev.db\nCLIENT_URL=http://localhost:5173\n`
  );
  fs.writeFileSync(
    path.join(target, '.gitignore'),
    'node_modules/\n.env\ndist/\n*.db\n.DS_Store\n'
  );
  fs.writeFileSync(
    path.join(target, 'docker-compose.yml'),
    `services:\n  api:\n    build: ./apps/api\n    ports: ["4000:4000"]\n    environment:\n      PORT: 4000\n      JWT_SECRET: docker-secret\n      DATABASE_URL: file:./dev.db\n  web:\n    build: ./apps/web\n    ports: ["5173:80"]\n    depends_on: [api]\n`
  );
  fs.mkdirSync(path.join(target, '.github/workflows'), { recursive: true });
  fs.writeFileSync(
    path.join(target, '.github/workflows/ci.yml'),
    `name: CI\non: [push, pull_request]\njobs:\n  build:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-node@v4\n        with: { node-version: 20 }\n      - run: npm install\n      - run: npm test\n      - run: npm run build\n`
  );
  fs.writeFileSync(
    path.join(target, 'README.md'),
    `# ${cfg.name}\n\nGenerated by **create-turbo-stack**.\n\nFrontend: **${cfg.frontend}** · Backend: **${cfg.backend}** · DB: **${cfg.db}**\n\n## Quick start\n\n\`\`\`bash\ncp .env.example .env\nnpm install\nnpm run db:push\nnpm run dev:api\nnpm run dev:web\n\`\`\`\n`
  );
}

async function main() {
  console.log('\ncreate-turbo-stack — full-stack scaffolder\n');
  const name = nameArg || (await ask('Project name', 'my-app'));
  const frontend = (flag('frontend') || (await ask('Frontend (react|vue|svelte)', 'react'))).toLowerCase();
  const backend = (flag('backend') || (await ask('Backend (express|fastify)', 'express'))).toLowerCase();
  const db = (flag('db') || (await ask('Database (sqlite|postgres)', 'sqlite'))).toLowerCase();

  if (!['react', 'vue', 'svelte'].includes(frontend)) {
    console.error('Invalid frontend');
    process.exit(1);
  }
  if (!['express', 'fastify'].includes(backend)) {
    console.error('Invalid backend');
    process.exit(1);
  }

  const target = path.resolve(process.cwd(), name);
  if (fs.existsSync(target) && fs.readdirSync(target).length) {
    console.error(`Directory not empty: ${target}`);
    process.exit(1);
  }
  fs.mkdirSync(target, { recursive: true });

  const vars = {
    PROJECT_NAME: name,
    FRONTEND: frontend,
    BACKEND: backend,
    DB_PROVIDER: db === 'postgres' ? 'postgresql' : 'sqlite',
    DATABASE_URL: db === 'postgres' ? 'postgresql://user:pass@localhost:5432/app' : 'file:./dev.db',
  };

  copyDir(path.join(TEMPLATES, `frontend-${frontend}`), path.join(target, 'apps/web'), vars);
  copyDir(path.join(TEMPLATES, `backend-${backend}`), path.join(target, 'apps/api'), vars);
  writeMergedRoot(target, { name, frontend, backend, db });

  // patch prisma provider if needed
  const schemaPath = path.join(target, 'apps/api/prisma/schema.prisma');
  if (fs.existsSync(schemaPath)) {
    let schema = fs.readFileSync(schemaPath, 'utf8');
    schema = schema.replace('provider = "sqlite"', `provider = "${vars.DB_PROVIDER}"`);
    fs.writeFileSync(schemaPath, schema);
  }

  console.log(`\n✔ Created ${name}`);
  console.log(`\n  cd ${name}`);
  console.log('  cp .env.example .env');
  console.log('  npm install');
  console.log('  npm run db:push');
  console.log('  npm run dev:api   # + npm run dev:web\n');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
